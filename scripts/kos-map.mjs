// Builds src/components/kosMap.ts: the coastline around Kos as one SVG path, from Natural Earth 1:10m (public domain).
// Run once, by hand; the page never fetches map data.
//   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_land.geojson
//   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_minor_islands.geojson
//   node scripts/kos-map.mjs ne_10m_land.geojson ne_10m_minor_islands.geojson
import { readFileSync, writeFileSync } from 'node:fs'

// Lon/lat frame around Kos: Kalymnos to the north-west, the Bodrum peninsula to the north-east, Nisyros to the south.
const WEST = 26.85
const EAST = 27.75
const SOUTH = 36.55
const NORTH = 37.2
const WIDTH = 800
// Equirectangular, scaled by cos(latitude) so kilometres east and north look the same.
const K = Math.cos((((SOUTH + NORTH) / 2) * Math.PI) / 180)
const HEIGHT = Math.round((WIDTH * (NORTH - SOUTH)) / ((EAST - WEST) * K))
const x = (lon) => ((lon - WEST) / (EAST - WEST)) * WIDTH
const y = (lat) => ((NORTH - lat) / (NORTH - SOUTH)) * HEIGHT

/** Sutherland–Hodgman: clip a ring to the frame, one edge at a time. */
function clip(ring) {
  const edges = [
    [(p) => p[0] >= WEST, (a, b) => cut(a, b, 0, WEST)],
    [(p) => p[0] <= EAST, (a, b) => cut(a, b, 0, EAST)],
    [(p) => p[1] >= SOUTH, (a, b) => cut(a, b, 1, SOUTH)],
    [(p) => p[1] <= NORTH, (a, b) => cut(a, b, 1, NORTH)],
  ]
  let out = ring
  for (const [inside, cross] of edges) {
    const input = out
    out = []
    for (let i = 0; i < input.length; i++) {
      const cur = input[i]
      const prev = input[(i + input.length - 1) % input.length]
      if (inside(cur)) {
        if (!inside(prev)) out.push(cross(prev, cur))
        out.push(cur)
      } else if (inside(prev)) out.push(cross(prev, cur))
    }
    if (out.length === 0) break
  }
  return out
}
function cut(a, b, axis, value) {
  const t = (value - a[axis]) / (b[axis] - a[axis])
  return [a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])]
}

/** Douglas–Peucker in screen units. */
function simplify(points, tolerance) {
  if (points.length < 3) return points
  let index = 0
  let far = 0
  const [a, b] = [points[0], points[points.length - 1]]
  for (let i = 1; i < points.length - 1; i++) {
    const d = distance(points[i], a, b)
    if (d > far) [far, index] = [d, i]
  }
  if (far <= tolerance) return [a, b]
  return [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)]
}
/** A closed ring starts and ends on the same point; simplify it as two open halves, or it collapses to a line. */
function simplifyRing(points, tolerance) {
  const last = points.at(-1)
  const open = points.length > 1 && last[0] === points[0][0] && last[1] === points[0][1] ? points.slice(0, -1) : points
  const middle = Math.floor(open.length / 2)
  return [...simplify(open.slice(0, middle + 1), tolerance).slice(0, -1), ...simplify(open.slice(middle), tolerance)]
}
function distance(p, a, b) {
  const [dx, dy] = [b[0] - a[0], b[1] - a[1]]
  const len = Math.hypot(dx, dy) || 1
  return Math.abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / len
}

const paths = []
for (const file of process.argv.slice(2)) {
  for (const feature of JSON.parse(readFileSync(file, 'utf8')).features) {
    const g = feature.geometry
    const polygons = g.type === 'Polygon' ? [g.coordinates] : g.coordinates
    for (const polygon of polygons) {
      for (const ring of polygon) {
        const inFrame = clip(ring)
        if (inFrame.length < 3) continue
        const screen = simplifyRing(
          inFrame.map(([lon, lat]) => [x(lon), y(lat)]),
          0.6,
        )
        if (screen.length < 3) continue
        paths.push(`M${screen.map(([px, py]) => `${px.toFixed(1)} ${py.toFixed(1)}`).join('L')}Z`)
      }
    }
  }
}

const out = `// Generated by scripts/kos-map.mjs from Natural Earth 1:10m land and minor islands (public domain). Do not edit by hand.
export const MAP = {
  /** Frame in degrees. */
  west: ${WEST},
  east: ${EAST},
  south: ${SOUTH},
  north: ${NORTH},
  width: ${WIDTH},
  height: ${HEIGHT},
  /** All land in the frame, one SVG path in the frame's units (north up). */
  land: '${paths.join('')}',
}

/** A point in the frame's units for a longitude and latitude. */
export function mapPoint(lon: number, lat: number): [number, number] {
  return [((lon - MAP.west) / (MAP.east - MAP.west)) * MAP.width, ((MAP.north - lat) / (MAP.north - MAP.south)) * MAP.height]
}
`
writeFileSync(new URL('../src/components/kosMap.ts', import.meta.url), out)
console.log(`kosMap.ts: ${paths.length} shapes, ${out.length} bytes, ${WIDTH}×${HEIGHT}`)
